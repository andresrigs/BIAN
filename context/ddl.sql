-- BIAN Cards & Deposits star schema (Snowflake). Derived from BIAN Semantic API r14.0.0 control records / behavior qualifiers.
CREATE SCHEMA IF NOT EXISTS BIAN_DEMO.BIAN;

-- BIAN Branch Location Management: servicing branch / booking location (BankBranchLocationReference).
CREATE OR REPLACE TABLE DIM_BRANCH (
  BRANCH_ID NUMBER(38,0),
  BRANCH_NAME VARCHAR,
  BRANCH_TYPE VARCHAR,
  BRANCH_REGION VARCHAR,
  BRANCH_COUNTRY VARCHAR,
  CONSTRAINT PK_DIM_BRANCH PRIMARY KEY (BRANCH_ID)
);

-- BIAN Credit Card service domain, CreditCardFacility control record: card account with credit plan, network and status.
CREATE OR REPLACE TABLE DIM_CARD_ACCOUNT (
  CARD_ACCOUNT_ID NUMBER(38,0),
  CARD_ACCOUNT_NUMBER VARCHAR,
  PARTY_ID NUMBER(38,0),
  PRODUCT_ID NUMBER(38,0),
  CARD_NETWORK VARCHAR,
  CREDIT_PLAN_TYPE VARCHAR,
  ACCOUNT_STATUS VARCHAR,
  BILLING_CYCLE_DAY NUMBER(38,0),
  OPEN_DATE DATE,
  CONSTRAINT PK_DIM_CARD_ACCOUNT PRIMARY KEY (CARD_ACCOUNT_ID)
);

-- Channel through which a transaction was initiated (BIAN Channels business area: Branch, ATM, POS, eCommerce, Mobile, Online).
CREATE OR REPLACE TABLE DIM_CHANNEL (
  CHANNEL_ID NUMBER(38,0),
  CHANNEL_NAME VARCHAR,
  CHANNEL_TYPE VARCHAR,
  CONSTRAINT PK_DIM_CHANNEL PRIMARY KEY (CHANNEL_ID)
);

-- ISO 4217 currency reference (AccountCurrency / CardTransactionCurrency).
CREATE OR REPLACE TABLE DIM_CURRENCY (
  CURRENCY_CODE VARCHAR,
  CURRENCY_NAME VARCHAR,
  CONSTRAINT PK_DIM_CURRENCY PRIMARY KEY (CURRENCY_CODE)
);

-- Calendar date dimension at day grain (Gregorian). Shared by every BIAN fact via role-played date keys.
CREATE OR REPLACE TABLE DIM_DATE (
  DATE_KEY NUMBER(38,0),
  FULL_DATE DATE,
  DATE_NAME VARCHAR,
  YEAR_NUM NUMBER(38,0),
  YEAR_NAME VARCHAR,
  QUARTER_KEY NUMBER(38,0),
  QUARTER_NAME VARCHAR,
  QUARTER_OF_YEAR NUMBER(38,0),
  MONTH_KEY NUMBER(38,0),
  MONTH_NAME VARCHAR,
  MONTH_OF_YEAR NUMBER(38,0),
  DAY_OF_WEEK_NAME VARCHAR,
  CONSTRAINT PK_DIM_DATE PRIMARY KEY (DATE_KEY)
);

-- BIAN Current Account / Savings Account / Term Deposit / Corporate Current Account facility control records: deposit account master.
CREATE OR REPLACE TABLE DIM_DEPOSIT_ACCOUNT (
  DEPOSIT_ACCOUNT_ID NUMBER(38,0),
  ACCOUNT_NUMBER VARCHAR,
  PARTY_ID NUMBER(38,0),
  PRODUCT_ID NUMBER(38,0),
  ACCOUNT_TYPE VARCHAR,
  ACCOUNT_STATUS VARCHAR,
  INTEREST_RATE_TYPE VARCHAR,
  TERM_MONTHS NUMBER(38,0),
  ROLLOVER_INSTRUCTION VARCHAR,
  OPEN_DATE DATE,
  MATURITY_DATE DATE,
  CONSTRAINT PK_DIM_DEPOSIT_ACCOUNT PRIMARY KEY (DEPOSIT_ACCOUNT_ID)
);

-- BIAN Issued Device Administration, IssuedDeviceAllocation control record: physical cards, virtual cards and tokens.
CREATE OR REPLACE TABLE DIM_ISSUED_DEVICE (
  ISSUED_DEVICE_ID NUMBER(38,0),
  MASKED_PAN VARCHAR,
  CARD_ACCOUNT_ID NUMBER(38,0),
  DEVICE_TYPE VARCHAR,
  DEVICE_STATUS VARCHAR,
  ISSUE_DATE DATE,
  EXPIRY_DATE DATE,
  CONSTRAINT PK_DIM_ISSUED_DEVICE PRIMARY KEY (ISSUED_DEVICE_ID)
);

-- BIAN Merchant Relations / Merchant Acquiring Facility: merchant with MCC classification and acquirer.
CREATE OR REPLACE TABLE DIM_MERCHANT (
  MERCHANT_ID NUMBER(38,0),
  MERCHANT_NAME VARCHAR,
  MCC_CODE VARCHAR,
  MCC_CATEGORY VARCHAR,
  MERCHANT_COUNTRY VARCHAR,
  ACQUIRER_NAME VARCHAR,
  CONSTRAINT PK_DIM_MERCHANT PRIMARY KEY (MERCHANT_ID)
);

-- BIAN Party Reference Data Directory: customer / party master (PartyType, demographics, bank relations).
CREATE OR REPLACE TABLE DIM_PARTY (
  PARTY_ID NUMBER(38,0),
  PARTY_NAME VARCHAR,
  PARTY_TYPE VARCHAR,
  CUSTOMER_SEGMENT VARCHAR,
  PARTY_STATUS VARCHAR,
  KYC_STATUS VARCHAR,
  COUNTRY_NAME VARCHAR,
  STATE_NAME VARCHAR,
  CITY_NAME VARCHAR,
  ONBOARDING_DATE DATE,
  CONSTRAINT PK_DIM_PARTY PRIMARY KEY (PARTY_ID)
);

-- BIAN Product Directory: product instance catalogue, classified by BIAN Business Area, Business Domain and fulfilling Service Domain.
CREATE OR REPLACE TABLE DIM_PRODUCT (
  PRODUCT_ID NUMBER(38,0),
  PRODUCT_CODE VARCHAR,
  PRODUCT_NAME VARCHAR,
  PRODUCT_LINE VARCHAR,
  BIAN_BUSINESS_AREA VARCHAR,
  BIAN_BUSINESS_DOMAIN VARCHAR,
  BIAN_SERVICE_DOMAIN VARCHAR,
  INTEREST_BEARING_FLAG VARCHAR,
  CONSTRAINT PK_DIM_PRODUCT PRIMARY KEY (PRODUCT_ID)
);

-- Month-end card account position (BIAN Credit Card: CreditPlan, Billing, Interest, Charge, Repayment BQs; Card Collections delinquency).
CREATE OR REPLACE TABLE FACT_CARD_ACCOUNT_SNAPSHOT (
  CARD_ACCOUNT_ID NUMBER(38,0),
  SNAPSHOT_DATE_KEY NUMBER(38,0),
  PARTY_ID NUMBER(38,0),
  PRODUCT_ID NUMBER(38,0),
  BRANCH_ID NUMBER(38,0),
  CURRENCY_CODE VARCHAR,
  CREDIT_LIMIT_AMT NUMBER(18,4),
  OUTSTANDING_BALANCE_AMT NUMBER(18,4),
  AVAILABLE_CREDIT_AMT NUMBER(18,4),
  STATEMENT_BALANCE_AMT NUMBER(18,4),
  MIN_PAYMENT_DUE_AMT NUMBER(18,4),
  PAST_DUE_AMT NUMBER(18,4),
  DAYS_PAST_DUE NUMBER(38,0),
  DELINQUENCY_BUCKET VARCHAR,
  INTEREST_CHARGED_AMT NUMBER(18,4),
  FEES_CHARGED_AMT NUMBER(18,4),
  PAYMENTS_RECEIVED_AMT NUMBER(18,4),
  REWARD_POINTS_BALANCE NUMBER(38,0)
);

-- Card disputes, chargebacks and fraud claims (BIAN Card Case: Chargeback, Arbitration, Resolution BQs).
CREATE OR REPLACE TABLE FACT_CARD_CASE (
  CARD_CASE_ID NUMBER(38,0),
  CARD_TXN_ID NUMBER(38,0),
  CARD_ACCOUNT_ID NUMBER(38,0),
  PARTY_ID NUMBER(38,0),
  PRODUCT_ID NUMBER(38,0),
  MERCHANT_ID NUMBER(38,0),
  CASE_OPENED_DATE_KEY NUMBER(38,0),
  CASE_CLOSED_DATE_KEY NUMBER(38,0),
  CARD_CASE_TYPE VARCHAR,
  CASE_STATUS VARCHAR,
  RESOLUTION_OUTCOME VARCHAR,
  DISPUTED_AMT NUMBER(18,4),
  CHARGEBACK_AMT NUMBER(18,4),
  RECOVERED_AMT NUMBER(18,4),
  DAYS_TO_RESOLVE NUMBER(38,0),
  CONSTRAINT PK_FACT_CARD_CASE PRIMARY KEY (CARD_CASE_ID)
);

-- Card transaction at authorization/capture grain (BIAN Card Authorization, Card Transaction Capture, Credit Card Position Keeping).
CREATE OR REPLACE TABLE FACT_CARD_TRANSACTION (

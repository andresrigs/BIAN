  REWARD_POINTS_EARNED NUMBER(38,0),
  CARD_PRESENT_FLAG NUMBER(38,0),
  CROSS_BORDER_FLAG NUMBER(38,0),
  FRAUD_FLAG NUMBER(38,0),
  CONSTRAINT PK_FACT_CARD_TRANSACTION PRIMARY KEY (CARD_TXN_ID)
);

-- Month-end deposit account position (BIAN Current/Savings/Term Deposit/Corporate Current Account: AmountBlock, Interest, Charge BQs).
CREATE OR REPLACE TABLE FACT_DEPOSIT_ACCOUNT_SNAPSHOT (
  DEPOSIT_ACCOUNT_ID NUMBER(38,0),
  SNAPSHOT_DATE_KEY NUMBER(38,0),
  PARTY_ID NUMBER(38,0),
  PRODUCT_ID NUMBER(38,0),
  BRANCH_ID NUMBER(38,0),

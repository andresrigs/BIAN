  MERCHANT_ID NUMBER(38,0),
  CHANNEL_ID NUMBER(38,0),
  CURRENCY_CODE VARCHAR,
  TXN_DATE_KEY NUMBER(38,0),
  POSTING_DATE_KEY NUMBER(38,0),
  CARD_TXN_TYPE VARCHAR,
  AUTH_DECISION VARCHAR,
  DECLINE_REASON VARCHAR,
  ENTRY_MODE VARCHAR,
  TXN_AMT NUMBER(18,4),
  INTERCHANGE_FEE_AMT NUMBER(18,4),
